import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const crateDirectory = resolve(repositoryRoot, 'wasm/blp-jpeg-decoder');
const outputPath = resolve(repositoryRoot, 'blp/wasm/blpJpegDecoderBytes.ts');
const wasmPath = resolve(
    crateDirectory,
    'target/wasm32-unknown-unknown/release/war3_model_blp_jpeg_decoder.wasm'
);
const checkOnly = process.argv.includes('--check');
const rustFlags = [
    '-Ctarget-feature=+simd128',
    `--remap-path-prefix=${repositoryRoot}=/war3-model`,
    `--remap-path-prefix=${homedir()}=/user`
].join('\x1f');

const build = spawnSync(
    'cargo',
    ['build', '--locked', '--release', '--target', 'wasm32-unknown-unknown'],
    {
        cwd: crateDirectory,
        encoding: 'utf8',
        env: {
            ...process.env,
            CARGO_ENCODED_RUSTFLAGS: rustFlags,
            CARGO_INCREMENTAL: '0',
            SOURCE_DATE_EPOCH: '0'
        }
    }
);

if (build.stdout) process.stdout.write(build.stdout);
if (build.stderr) process.stderr.write(build.stderr);
if (build.status !== 0) {
    process.exit(build.status ?? 1);
}

const wasm = await readFile(wasmPath);
const sha256 = createHash('sha256').update(wasm).digest('hex');
const source = `// Generated by scripts/build-blp-wasm.mjs. Do not edit.\n`
    + `export const BLP_JPEG_DECODER_WASM_SHA256 = '${sha256}';\n`
    + `export const BLP_JPEG_DECODER_WASM_BASE64 = '${wasm.toString('base64')}';\n`;

if (checkOnly) {
    let existing;
    try {
        existing = await readFile(outputPath, 'utf8');
    } catch {
        existing = undefined;
    }
    if (existing !== source) {
        process.stderr.write(
            `${outputPath} is stale. Run npm run build-blp-wasm and commit the result.\n`
        );
        process.exit(1);
    }
    process.stdout.write(
        `Verified ${outputPath} (${wasm.length} bytes, sha256 ${sha256})\n`
    );
} else {
    await mkdir(dirname(outputPath), {recursive: true});
    await writeFile(outputPath, source, 'utf8');
    process.stdout.write(
        `Wrote ${outputPath} (${wasm.length} bytes, sha256 ${sha256})\n`
    );
}
